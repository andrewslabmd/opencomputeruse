import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, readFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { parse } from 'yaml';
import { Host } from '../../packages/host/server.mjs';
import { Broker } from '../../packages/host/broker.mjs';
import { RecentCalls, issueUrl, redact, REPORTS_FILE } from '../../packages/mcp/report.mjs';
const issue = { summary: 'type with replace=true kept the old text', expected: 'The field holds only the new text.', what_happened: 'The new text was appended; status ok.', workaround: 'Selected all with a hotkey first.', severity: 'major' };
const formIds = async () => parse(await readFile('.github/ISSUE_TEMPLATE/bug_report.yml', 'utf8')).body.map(field => field.id);
const reports = async directory => (await readFile(join(directory, REPORTS_FILE), 'utf8')).trim().split('\n').map(line => JSON.parse(line));
test('report_issue saves locally and links to the bug form with names of recent calls only', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'ocu-report-'));
  const backend = { async call() { return { content: [{ type: 'text', text: 'private document text' }] }; }, async stop() {}, async reset() {} };
  const host = new Host({ directory, broker: backend }); await host.start();
  const client = new Broker(process.execPath, ['packages/cli/main.mjs', 'mcp'], { ...process.env, OCU_RUNTIME_DIR: directory });
  t.after(async () => { await client.stop(); await host.close(); await rm(directory, { recursive: true, force: true }); });
  const tool = (await client.list()).tools.find(t => t.name === 'report_issue');
  assert.match(tool.description, /once/); assert.match(tool.description, /continue/); assert.match(tool.description, /Nothing is sent/);
  await client.call('computer_use_observe', { app_target: 'Secret Notes' });
  await client.call('computer_use_action_batch', { actions: [{ kind: 'type', at: { x: 1, y: 1 }, text: 'my secret words' }, { kind: 'hotkey', keys: ['cmd', 'a'] }] });
  const result = JSON.parse((await client.call('report_issue', issue)).content[0].text);
  assert.equal(result.status, 'saved'); assert.match(result.next, /Nothing was sent/); assert.match(result.next, /check/);
  const [saved] = await reports(directory);
  assert.equal(saved.id, result.report_id); assert.equal(saved.client.name, 'opencomputeruse-host'); assert.ok(saved.version && saved.commit && saved.macos && saved.mac_model);
  assert.deepEqual(saved.recent_calls, [{ tool: 'computer_use_observe', outcome: 'ok' }, { tool: 'computer_use_action_batch', outcome: 'observation_required', actions: ['type', 'hotkey'] }]);
  const serialized = JSON.stringify(saved);
  for (const content of ['Secret Notes', 'my secret words', 'private document text']) assert.ok(!serialized.includes(content), content);
  const url = new URL(result.issue_url);
  assert.equal(url.origin + url.pathname, 'https://github.com/andrewslabmd/opencomputeruse/issues/new');
  assert.equal(url.searchParams.get('template'), 'bug_report.yml'); assert.equal(url.searchParams.get('title'), issue.summary);
  const ids = await formIds();
  for (const key of url.searchParams.keys()) if (!['template', 'title'].includes(key)) assert.ok(ids.includes(key), `${key} is a field of the bug form`);
  for (const id of ['what', 'reproduce', 'version', 'environment']) assert.ok(url.searchParams.get(id), id);
  assert.match(url.searchParams.get('what'), /Workaround: Selected all/); assert.match(url.searchParams.get('reproduce'), /computer_use_action_batch \[type, hotkey\]: observation_required/);
  // Asked again with the same summary: the same report, not a second one.
  assert.equal(JSON.parse((await client.call('report_issue', issue)).content[0].text).status, 'already_reported');
  assert.equal((await reports(directory)).length, 1);
  const invalid = await client.call('report_issue', { summary: 'x', severity: 'major' });
  assert.equal(invalid.isError, true); assert.match(invalid.content[0].text, /expected is required/);
});
test('report_issue works without a running host and never connects to it', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'ocu-report-'));
  const client = new Broker(process.execPath, ['packages/cli/main.mjs', 'mcp'], { ...process.env, OCU_RUNTIME_DIR: directory });
  t.after(async () => { await client.stop(); await rm(directory, { recursive: true, force: true }); });
  const result = await client.call('report_issue', { ...issue, workaround: undefined, severity: 'blocker' });
  assert.equal(result.isError, undefined);
  const [saved] = await reports(directory);
  assert.deepEqual(saved.recent_calls, []); assert.ok(!new URL(saved.issue_url).searchParams.get('what').includes('Workaround'));
});
test('the link leaves out home paths, the account name, email addresses and URL queries', () => {
  const options = { home: '/Users/jdoe', user: 'jdoe' };
  assert.equal(redact('Opened /Users/jdoe/Documents/plan.txt for jdoe (jane@example.com) at https://app.example.com/doc?token=abc', options), 'Opened ~/Documents/plan.txt for [user] ([email]) at https://app.example.com/doc?[removed]');
  const recent = new RecentCalls(2);
  for (const kind of ['click', 'type', 'Bad Kind!']) recent.record('computer_use_action_batch', { actions: [{ kind }] }, 'ok');
  assert.deepEqual(recent.items.map(c => c.actions), [['type'], ['invalid']]);
  const url = new URL(issueUrl({ id: 'abcd1234', summary: 'Fails in /Users/jdoe/x', expected: 'a', what_happened: 'mail jane@example.com', workaround: '', severity: 'minor', version: '0.1.0', commit: 'abc1234', macos: '26.0', mac_model: 'Mac15,8', chip: 'Apple M3', client: { name: 'claude-code', version: '2.1.0' }, recent_calls: [] }, options));
  assert.equal(url.searchParams.get('title'), 'Fails in ~/x'); assert.match(url.searchParams.get('what'), /mail \[email\]/);
  assert.equal(url.searchParams.get('environment'), 'macOS 26.0, Mac15,8 (Apple M3), claude-code 2.1.0');
});
